"""Two-pair diagnostic: does per-pair GS identity change the baseline outcome?

Context
-------
The frozen `design.json` declares "one independent evaluator-only identity per
pair (message/key/nonce from the pair reference seed)". The executed 50 pairs
all used `offset=0`, so every pair shared one identity
(see private_eval/confirmation100_baseline_20261102T204500Z: 50 byte-identical
.bin files, first 32 bytes == MESSAGES[0]).

This script runs the SAME attack on two pairs with the identity the design
declared, and reports both the own-identity score and the old shared-identity
score, so the two settings can be compared pair by pair.

This is a DIAGNOSTIC, not a frozen-protocol run. It writes only to its own
output directory and does not touch the frozen baseline run.

For each pair:
  offset = reference_seed % 10000        (per-pair identity, official crypto lists)
  reference generated by the TARGET from zT(own identity)
  Imprint 30 updates in the PROXY
  evaluation: target 50-step DDIM inversion, then bit accuracy under
              (a) own identity  (b) offset=0 shared identity
"""
import json
import math
import sys
import time
from pathlib import Path

import numpy as np
import torch
from PIL import Image

ROOT = Path('/data0/liyanlei/watermark_research')
sys.path.insert(0, str(ROOT / 'scripts/confirmation100'))
sys.path.insert(0, str(ROOT / 'scripts/defense'))
import common100 as m  # noqa: E402
from sembind_smoke import imprint_attack  # noqa: E402

THRESHOLD = 0.70703125
STEPS = 30


def psnr_rgb01(image, cover):
    a = np.asarray(image, dtype=np.float64) / 255.0
    b = np.asarray(cover, dtype=np.float64) / 255.0
    mse = float(np.mean((a - b) ** 2))
    return None if mse == 0 else -10.0 * math.log10(mse)


def fingerprint(wm):
    raw = wm.messages[0] + wm.keys[0] + wm.nonces[0]
    import hashlib
    return hashlib.sha256(raw).hexdigest()


def main(out_dir, task_ids='1,2', device='cuda:0'):
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    wanted = [int(x) for x in str(task_ids).split(',')]

    design = m.c.read(ROOT / 'protocols/confirmation100_design_v7.json')
    proxy = dict(design['proxy'])
    provider = m.r.official_provider(design['target'])
    from utils.wm.gs_provider import GsProvider

    def make_wm(offset):
        return GsProvider(latent_shape=(1, 4, 64, 64), device=device, dtype=torch.float32,
                          message_width_in_bytes=32, num_replications=64, l=1, offset=offset)

    wm_shared = make_wm(0)
    shared_fp = fingerprint(wm_shared)

    rows = []
    for task in design['tasks']:
        sid = task['id']
        if sid not in wanted:
            continue
        start = time.time()
        offset = int(task['reference_seed']) % 10000
        wm_own = make_wm(offset)
        own_fp = fingerprint(wm_own)

        # reference: target generates from the per-pair identity latent
        r_det = m.r.deterministic(task['reference_seed'])
        z = wm_own.get_wm_latents()['zT_torch']
        with torch.no_grad():
            ref = provider.generate(prompts=[task['reference_prompt']], num_inference_steps=50,
                                    guidance_scale=7.5, latents=z, return_latents=False)['images_PIL'][0]
        ref.save(out / (str(sid) + '_reference.png'))
        np.save(out / (str(sid) + '_own_noise.npy'), z.detach().float().cpu().numpy())

        with Image.open(ROOT / task['cover']) as im:
            cover = im.convert('RGB')
        cover.save(out / (str(sid) + '_cover.png'))

        def score(image, wm):
            with torch.no_grad():
                zi = provider.invert_images(image, num_inference_steps=50)['zT_torch']
            return float(wm.get_accuracies(zi)['bit_accuracies'][0])

        ref_own = score(ref, wm_own)
        ref_shared = score(ref, wm_shared)

        # attack: proxy optimises the cover toward the inverted reference
        cand = imprint_attack(provider, proxy['snapshot'], cover, ref, STEPS, device)
        cand.save(out / (str(sid) + '_forged.png'))

        cand_own = score(cand, wm_own)
        cand_shared = score(cand, wm_shared)

        row = dict(
            task_id=sid,
            reference_seed=task['reference_seed'],
            offset=offset,
            identity_own=own_fp,
            identity_shared=shared_fp,
            identities_differ=own_fp != shared_fp,
            reference_ba_own=ref_own,
            reference_ba_shared=ref_shared,
            candidate_ba_own=cand_own,
            candidate_ba_shared=cand_shared,
            candidate_pass_own=bool(cand_own > THRESHOLD),
            candidate_pass_shared=bool(cand_shared > THRESHOLD),
            psnr_db=psnr_rgb01(cand, cover),
            steps=STEPS,
            seconds=time.time() - start,
        )
        rows.append(row)
        m.c.write(out / (str(sid) + '_result.json'), row)
        print('PAIR_DONE', json.dumps(row, ensure_ascii=False), flush=True)

    # baseline recorded values (shared identity, offset=0) for the same tasks
    baseline = {}
    base_path = ROOT / 'runs/confirmation100_baseline_20261102T204500Z/analysis_s30.json'
    if base_path.exists():
        for r0 in json.loads(base_path.read_text(encoding='utf-8'))['rows']:
            if r0['label'] == '30':
                baseline[r0['task_id']] = dict(bit_accuracy=r0['bit_accuracy'], psnr_db=r0['psnr_db'])
    for row in rows:
        b = baseline.get(row['task_id'])
        if b:
            row['baseline_recorded_ba'] = b['bit_accuracy']
            row['baseline_recorded_psnr_db'] = b['psnr_db']
            row['delta_ba_vs_baseline'] = row['candidate_ba_own'] - b['bit_accuracy']

    summary = dict(
        diagnostic='two_pair_per_pair_identity',
        frozen_protocol=False,
        device=device,
        steps=STEPS,
        threshold=THRESHOLD,
        rows=rows,
    )
    m.c.write(out / 'summary.json', summary)
    print('SUMMARY', json.dumps(summary, ensure_ascii=False, indent=2), flush=True)


if __name__ == '__main__':
    main(*sys.argv[1:])
